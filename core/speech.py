# -*- coding: utf-8 -*-
"""발음 대본 — **자막으로 읽는 글과 소리로 읽는 글은 다르다.**

2026-08-14, 영상 만드는 쪽에서 온 말:

    "자막 대본은 있는데 발음 대본은 없네요. 「1946년」·「GDP」 같은 것을
     TTS 가 잘못 읽을 수 있습니다."

맞는 지적이다. 우리가 쓴 `data-say` 는 **자막으로는 그대로 맞다** — 눈은 「1946년」과
「GDP」를 그대로 읽는 것이 편하다. 하지만 귀로 가는 글은 다르다. TTS 는 「1946」을
「일구사육」으로 끊어 읽거나 「GDP」를 영어로 발음해 버린다.

그래서 **같은 글을 두 벌로 낸다.**

    data-say   1946년 고용법은 GDP 를 25% 끌어올렸다   ← 자막. 눈으로 읽는 글
    data-read  천구백사십육 년 고용법은 지디피 를 …    ← 소리. 귀로 듣는 글

★ **모델을 안 부른다.** 숫자와 약어를 소리로 바꾸는 일은 규칙이 정확하고, 공짜고,
  매번 같은 답이 나온다. 모델에게 시키면 같은 문장이 어제와 오늘 다르게 읽히고,
  그 차이를 아무도 못 잡는다.

★ **자막 쪽은 안 건드린다.** 발음 대본은 덧붙이는 것이지 대체하는 것이 아니다.
  「이십오 퍼센트」가 화면에 뜨면 그것대로 읽기 나쁘다.
"""
from __future__ import annotations

import re
from typing import Dict

# ── 한자어 수사 ────────────────────────────────────────────────────────────
_D = "영일이삼사오육칠팔구"
_SMALL = ["", "십", "백", "천"]
_BIG = ["", "만", "억", "조", "경"]


def sino(n: int) -> str:
    """한자어로 읽은 수. `1946` → `천구백사십육`, `25000` → `이만 오천`.

    ★ 「일천·일백·일십」이 아니라 **「천·백·십」**이다. 만 자리 위에서는 「일만」도
      안 읽는다(우리말은 「일만 오천」이 아니라 「만 오천」이다). 다만 「일억」·「일조」는
      그대로 읽는다 — 「억 오천만」이라고는 안 한다.
    """
    if n == 0:
        return "영"
    if n < 0:
        return "마이너스 " + sino(-n)

    groups = []                               # 만 단위로 네 자리씩
    while n:
        groups.append(n % 10000)
        n //= 10000

    out = []
    for i in range(len(groups) - 1, -1, -1):
        g = groups[i]
        if not g:
            continue
        chunk = ""
        for j in range(3, -1, -1):
            d = (g // (10 ** j)) % 10
            if not d:
                continue
            # 십·백·천 앞의 「일」은 안 읽는다. 일의 자리(j=0)는 읽는다.
            chunk += ("" if d == 1 and j > 0 else _D[d]) + _SMALL[j]
        # 「일만」은 「만」으로. 억·조는 「일억」·「일조」로 읽는다.
        if g == 1 and i == 1:
            chunk = ""
        out.append(chunk + _BIG[i])
    return " ".join(x for x in out if x)


# ── 영문 약어 ──────────────────────────────────────────────────────────────
_ALPHA = {
    "A": "에이", "B": "비", "C": "씨", "D": "디", "E": "이", "F": "에프",
    "G": "지", "H": "에이치", "I": "아이", "J": "제이", "K": "케이", "L": "엘",
    "M": "엠", "N": "엔", "O": "오", "P": "피", "Q": "큐", "R": "알",
    "S": "에스", "T": "티", "U": "유", "V": "브이", "W": "더블유",
    "X": "엑스", "Y": "와이", "Z": "지",
}

# 글자마다 읽으면 어색한 것들. **여기 없는 약어는 한 글자씩 읽는다** — 그 편이
# 안전하다(모르는 낱말을 영어로 발음시키면 아무도 못 알아듣는다).
WORDS: Dict[str, str] = {
    "GDP": "지디피", "GNP": "지엔피", "CPI": "씨피아이", "PPI": "피피아이",
    "AD": "에이디", "AS": "에이에스", "AI": "에이아이", "IT": "아이티",
    "OECD": "오이씨디", "IMF": "아이엠에프", "WTO": "더블유티오",
    "FRB": "에프알비", "GM": "지엠", "R&D": "알앤디",
    "NX": "엔엑스", "MPC": "엠피씨", "MPS": "엠피에스",
}


def _abbr(m: re.Match) -> str:
    w = m.group(0)
    if w in WORDS:
        return WORDS[w]
    return "".join(_ALPHA.get(ch, ch) for ch in w)


# ── 단위 ───────────────────────────────────────────────────────────────────
# 숫자 뒤에 붙는 말. 붙여 읽으면 「천구백사십육년」처럼 뭉치므로 한 칸 띄운다.
_UNIT_SPACE = re.compile(r"(?<=[가-힣])(?=[가-힣])")


def _num(s: str) -> str:
    """`25,000` → `이만 오천`. `3.5` → `삼 점 오`.

    ★ 끝에 붙은 쉼표를 떼고 시작한다. 「25%까지 치솟았고, 일본은」 같은 문장에서
      정규식이 「,」 를 수의 일부로 물어 오는데, 그대로 int() 에 넣으면 터진다.
    """
    s = s.strip(", ")
    if not s or not any(c.isdigit() for c in s):
        return s
    s = s.replace(",", "")
    if "." in s:
        a, b = s.split(".", 1)
        return sino(int(a or 0)) + " 점 " + " ".join(_D[int(c)] for c in b if c.isdigit())
    return sino(int(s))


def to_read(text: str) -> str:
    """자막용 글 → **소리로 읽을 글.**

    바꾸는 것은 넷뿐이다: 영문 약어 · 숫자 · 기호 · 대시. 나머지 문장은 그대로
    둔다 — 우리말 문장을 다시 쓰기 시작하면 그건 규칙이 아니라 번역이 된다.
    """
    t = text or ""

    # 1) 통화 기호가 앞에 붙은 것 — `$25,000` → `이만 오천 달러`
    t = re.sub(r"\$\s?([\d,]+(?:\.\d+)?)", lambda m: f"{_num(m.group(1))} 달러", t)
    t = re.sub(r"₩\s?([\d,]+(?:\.\d+)?)", lambda m: f"{_num(m.group(1))} 원", t)

    # 2) 퍼센트 — `25%` → `이십오 퍼센트`
    t = re.sub(r"([\d,]+(?:\.\d+)?)\s?%", lambda m: f"{_num(m.group(1))} 퍼센트", t)

    # 3) 범위·기호. `1930~40년` 의 물결은 「에서」로, 대시는 쉼표로 끊는다.
    #    ★ 대시(—)를 그냥 두면 TTS 가 통째로 삼켜 두 문장이 붙어 읽힌다.
    t = re.sub(r"\s?[~∼]\s?", " 에서 ", t)
    t = re.sub(r"\s?[—–]\s?", ", ", t)
    t = t.replace("−", " 마이너스 ").replace("×", " 곱하기 ").replace("÷", " 나누기 ")

    # 4) 영문 약어 — 낱말 경계로 잡는다(소문자가 섞인 낱말은 안 건드린다)
    t = re.sub(r"\b[A-Z][A-Z&]{1,7}\b", _abbr, t)

    # 5) 남은 숫자. **단위와 붙어 있으면 한 칸 띄운다** — 「천구백사십육년」이 아니라
    #    「천구백사십육 년」이다. 붙여 두면 TTS 가 한 낱말로 뭉쳐 읽는다.
    #    ★ 조사 앞에서는 안 띄운다. 「0이 된다」가 「영 이 된다」가 되면 「이」가
    #      숫자 2 처럼 들린다 — 띄어쓰기 하나로 뜻이 바뀌는 자리다.
    t = re.sub(r"\d[\d,]*(?:\.\d+)?(?=[가-힣])(?![이가은는을를의도만과와에로])",
               lambda m: _num(m.group(0)) + " ", t)
    t = re.sub(r"\d[\d,]*(?:\.\d+)?", lambda m: _num(m.group(0)), t)

    # 6) 공백 정리. 앞의 규칙들이 낸 두 칸을 한 칸으로.
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s+([,.!?])", r"\1", t)
    return t


def differs(text: str) -> bool:
    """바꿀 것이 있었나. 없으면 `data-read` 를 아예 안 단다 — 같은 글을 두 번
    싣는 것은 받는 쪽에 「무엇이 다른가」를 찾게 시키는 일이다."""
    return to_read(text) != (text or "").strip()
